export const SONGS_BY_VENUE: Readonly<Record<VenueDefinition["id"], readonly SongDefinition[]>> = {
  "rusty-anchor": songs.filter((song) => song.venueId === "rusty-anchor"),
  "neon-cathedral": songs.filter((song) => song.venueId === "neon-cathedral"),
  "orbit-arena": songs.filter((song) => song.venueId === "orbit-arena"),
};

export const SONG_BY_ID: ReadonlyMap<string, SongDefinition> = new Map(
  songs.map((song) => [song.id, song]),
);

export const VENUE_BY_ID: ReadonlyMap<string, VenueDefinition> = new Map(
  VENUES.map((venue) => [venue.id, venue]),
);

export function songById(id: string): SongDefinition {
  const song = SONG_BY_ID.get(id);
  if (!song) throw new Error(`Unknown song: ${id}`);
  return song;
}

export function venueById(id: string): VenueDefinition {
  const venue = VENUE_BY_ID.get(id);
  if (!venue) throw new Error(`Unknown venue: ${id}`);
  return venue;
}
